/* a plain 32-bit hash of the flat's number, used as the seed - same flat,
 * same numbers ('47-a' is its own flat and gets its own) */
const seed = ( s ) => {
	let h = 2166136261;
	for ( const c of String( s ) ) h = Math.imul( h ^ c.charCodeAt( 0 ), 16777619 ) >>> 0;
	h = Math.imul( h ^ ( h >>> 15 ), 2246822519 ) >>> 0;
	return ( h ^ ( h >>> 13 ) ) >>> 0;
};
const rnd = ( s, i ) => ( seed( s + '#' + i ) % 10000 ) / 10000;

/* `plan` is the sales render of a layout, cropped out of the developer's own
 * poster (web/types/*.webp). Each is ONE real layout: `two.webp` is the
 * 78.8 + 9.6 m2 two-balcony flat (5, 26, 68, 173 - the one the old 3D show
 * flat was modelled from) and `one.webp` the 48.3 + 3.9 = 52.2 m2 one-bedroom.
 * A flat of exactly that layout shows it as fact; every other flat, and
 * every type card (a type spans several layouts), shows it as `ph`. The
 * flat's card also draws the flat's OWN plan from the drawing
 * (web/flatplans.json), which is true for every flat. */
const IMG_TWO = './types/two.webp', IMG_ONE = './types/one.webp';
const realImg = ( a ) =>
	a.inner === 78.8 && a.balcony === 9.6 ? IMG_TWO
		: a.inner === 48.3 && a.balcony === 3.9 ? IMG_ONE : null;

/* Rates are the sales office's, not the architect's: placeholders. */
const TYPE_DEF = [
	{ key: 'studio', rooms: 0, label: 'Studio', rate: ph( 905 ), img: IMG_ONE },
	{ key: 'one', rooms: 1, label: '1-bedroom', rate: ph( 880 ), img: IMG_ONE },
	{ key: 'two', rooms: 2, label: '2-bedroom', rate: ph( 835 ), img: IMG_TWO },
	{ key: 'three', rooms: 3, label: '3-bedroom', rate: ph( 800 ), img: IMG_TWO },
];

export const FLATS = PLAN_FLATS.map( ( p ) => {
	const t = TYPE_DEF.find( t => t.key === p.type );
	const fl = p.floor;
	// a flat is worth more the higher it stands, and the top two floors
	// carry a view premium - the sales office's rule, a placeholder here
	const lift = 1 + ( fl - 1 ) * 0.0075 + ( fl >= 8 ? 0.03 : 0 );
	const price = Math.round( p.area.total * t.rate.v * lift / 100 ) * 100;
	const s = rnd( p.n, 2 );
	const status = s > 0.78 ? 'available' : s > 0.70 ? 'reserved' : 'sold';
	const img = realImg( p.area );
	return {
		...p,
		/* the page's word for it: `rooms` is BEDROOMS (the filter's chips),
		 * `spaces` the rooms the drawing encloses, wet rooms and hall included */
		rooms: p.bedrooms, spaces: p.rooms,
		label: t.label,
		/* `area` on the page is the TOTAL (inner + balcony), the figure the
		 * architect's table sells by; `area.*` keeps all three */
		areaTotal: p.area.total,
		entrance: + p.core.slice( 1 ),            // C2 -> entrance 2
		balcony: p.area.balcony > 0,
		plan: img || ph( t.img ),
		price, status,
		ph: true,                                 // price and status are placeholders
	};
} );

export const flatByN = ( n ) => FLATS.find( f => f.n === String( n ) ) || null;

