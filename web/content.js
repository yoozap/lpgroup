/* ===================================================================== *
 *  The inventory
 *
 *  The building's real flats, from the architect's plans: web/flats.js is
 *  generated from them (tools/gen_flats.py) and carries each flat's own
 *  number, block, entrance, floor and printed areas. Nothing about a flat's
 *  size or place is invented here.
 *
 *  What the plans do NOT say is the price and whether it is still for
 *  sale. Those stay placeholders, seeded off the flat's own number so the
 *  list is the same on every reload, and every record says so (`ph: true`):
 *  ?ph=1 rings them on the page.
 * ===================================================================== */

